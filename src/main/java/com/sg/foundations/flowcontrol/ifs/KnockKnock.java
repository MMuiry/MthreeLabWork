package com.sg.foundations.flowcontrol.ifs;

import java.util.Scanner;

public class KnockKnock {

    public static void main(String[] args) {

        Scanner inputReader = new Scanner(System.in);

        System.out.print("Knock Knock! Guess who!! ");
        String nameGuess = inputReader.nextLine();

        if(nameGuess.equalsIgnoreCase("Marty McFly")){ //equalsIgnoreCase seems to be the best for singular changes. doing == for a object (like a string) will compare the object and not the value
            System.out.println("Hey! That's right! I'm back!");
            System.out.println(".... from the Future."); // Sorry, had to!
        }else{
            System.out.println("Dude, do I -look- like " + nameGuess);
        }
    }

}